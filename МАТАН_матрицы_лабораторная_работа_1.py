print("--- ЗАДАЧА 1 ---")

A1 = np.array([
    [3, 8, 1, 0],
    [4, 5, 7, 3],
    [1, 2, 0, 1]
])
B1 = np.array([
    [3, 4, 1, 1],
    [2, 5, 2, 3],
    [1, 7, 0, 0]
])
C1 = np.array([
    [4, 3, 1, 5],
    [2, 7, 8, 3],
    [1, 1, 3, 2]
])

# Вычисление выражения 4*A - 2*B + 3*C
Task1_Result = 4 * A1 - 2 * B1 + 3 * C1

print("Результат задачи 1 (4*A - 2*B + 3*C):")
print(Task1_Result)
print("\n" + "="*40 + "\n")


# ==========================================
# ЗАДАЧА 2 (Вариант 24)
# Найти произведение матриц (пункты а, б, в)
# ==========================================
print("--- ЗАДАЧА 2 ---")

# Пункт а)
A2_a = np.array([
    [0, 1],
    [2, 3]
])
B2_a = np.array([
    [2, 3],
    [8, -1]
])
Res2_a = np.matmul(A2_a, B2_a) 
print("Пункт а):")
print(Res2_a)

# Пункт б)
A2_b = np.array([
    [3, 5, 1],
    [4, 1, 2],
    [3, 2, 4]
])
B2_b = np.array([
    [4, 1, 2],
    [5, 0, 8],
    [1, 3, 0]
])
Res2_b = np.matmul(A2_b, B2_b)
print("\nПункт б):")
print(Res2_b)

# Пункт в)
A2_v = np.array([
    [2, 3, 0],
    [0, 1, -1]
])
B2_v = np.array([
    [1, 3],
    [0, 1],
    [3, -1]
])
Res2_v = np.matmul(A2_v, B2_v)
print("\nПункт в):")
print(Res2_v)
print("\n" + "="*40 + "\n")


