import numpy as np

# ==========================================
# ЗАДАНИЕ 1 (Вариант 24)
# Найти обратные матрицы для двух вариантов исходных данных
# ==========================================
print("=== ЗАДАНИЕ 1 ===")

# Исходные данные 1
A1 = np.array([
    [3, -5, 1],
    [-5, -4, -3],
    [6, 4, 2]
], dtype=float)

# Исходные данные 2
A2 = np.array([
    [3, 2, 0],
    [2, 1, 1],
    [1, 3, 1]
], dtype=float)

# Вычисление обратных матриц
inv_A1 = np.linalg.inv(A1)
inv_A2 = np.linalg.inv(A2)

print("1) Обратная матрица для Исходных данных 1:")
print(np.round(inv_A1, 4))

print("\n2) Обратная матрица для Исходных данных 2:")
print(np.round(inv_A2, 4))
print("\n" + "="*45 + "\n")


# ==========================================
# ЗАДАНИЕ 2 (Вариант 24)
# Найти ранг матрицы размера 4x5
# ==========================================
print("=== ЗАДАНИЕ 2 ===")

# Матрица варианта 24
M24 = np.array([
    [4, 2, 2, 7, 2],
    [-1, 1, 9, 0, 3],
    [0, -2, -1, 1, -3],
    [4, -12, 5, 9, 6]
], dtype=float)

# Вычисление ранга матрицы
rank_M24 = np.linalg.matrix_rank(M24)

print("Матрица:")
print(M24)
print(f"\nРанг матрицы r(A) = {rank_M24}")


